import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const deploymentManifest = resolve(here, "../../contracts/deployments/shannon-deployment.json");
const frontendManifest = resolve(here, "../../contracts/deployments/shannon-frontend.json");
const out = resolve(here, "../src/config/deployment.ts");

const deployment = JSON.parse(readFileSync(deploymentManifest, "utf8"));
const frontend = JSON.parse(readFileSync(frontendManifest, "utf8"));

const markets = frontend.markets
  .map(
    (market) => `  {
    symbol: "${market.symbol}",
    question: "${market.symbol} closes at or above its opening price",
    marketId: "${market.marketId}",
    market: "${market.market}",
    pool: "${market.pool}",
    marketNonce: ${market.marketNonce}n,
    yesId: ${market.yesId}n,
    noId: ${market.noId}n,
    yesGenerationKey: "${market.yesGenerationKey}",
    noGenerationKey: "${market.noGenerationKey}",
    tradingStart: ${market.tradingStart}n,
    expiry: ${market.expiry}n,
  }`,
  )
  .join(",\n");

const body = `// GENERATED by scripts/generate-deployment.mjs — do not edit.
// Sources: contracts/deployments/shannon-deployment.json and shannon-frontend.json
// Regenerate with: npm run generate:deployment

/** Immutable DreamMargin deployment bindings on Somnia Shannon. */
export const DEPLOYMENT = {
  chainId: ${deployment.chainId},
  deployedAtBlock: ${deployment.deployedAtBlock}n,
  controller: "${frontend.dreamMargin.controller}",
  vault: "${frontend.dreamMargin.vault}",
  oracle: "${frontend.dreamMargin.oracle}",
  reactiveObserver: "${frontend.dreamMargin.reactiveObserver}",
  seriesPolicyId: "${frontend.dreamMargin.seriesPolicyId}",
  module: "${frontend.dreamDex.binaryModule}",
  collateral: "${frontend.dreamDex.collateral}",
  outcomeToken: "${frontend.dreamDex.outcomeToken}",
  collateralDecimals: ${frontend.dreamDex.collateralDecimals},
  maxPositionPageSize: ${frontend.dreamMargin.maxPositionPageSize},
} as const;

/** Dedicated, long-lived DreamDEX generations supported by this client. */
export const MARKETS = [
${markets}
] as const;

export type Deployment = typeof DEPLOYMENT;
export type MarketDeployment = (typeof MARKETS)[number];
`;

writeFileSync(out, body);
console.log(`wrote ${out}`);
