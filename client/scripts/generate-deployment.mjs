import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const manifest = resolve(here, "../../contracts/deployments/shannon-deployment.json");
const out = resolve(here, "../src/config/deployment.ts");

const d = JSON.parse(readFileSync(manifest, "utf8"));

const body = `// GENERATED by scripts/generate-deployment.mjs — do not edit.
// Source: contracts/deployments/shannon-deployment.json
// Regenerate with: npm run generate:deployment

/** Immutable dreammargin deployment bindings on Somnia Shannon. */
export const DEPLOYMENT = {
  chainId: ${d.chainId},
  deployedAtBlock: ${d.deployedAtBlock}n,
  controller: "${d.controller}",
  vault: "${d.vault}",
  oracle: "${d.oracle}",
  module: "${d.dreamDexModule}",
  collateral: "${d.collateral}",
  outcomeToken: "${d.outcomeToken}",
} as const;

export type Deployment = typeof DEPLOYMENT;
`;

writeFileSync(out, body);
console.log(`wrote ${out}`);
